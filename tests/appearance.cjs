const assert = require('node:assert/strict');
const { DEFAULTS } = require('../src/core/constants');
const { remainingInfo, gradientAngle, cardTint, contrastText } = require('../src/core/appearance');
const { iso } = require('../src/core/dates');
const p = { settings: structuredClone(DEFAULTS), api: () => null };
const now = new Date(2026, 9, 24, 12);
const task = days => { const day = new Date(now); day.setDate(day.getDate() + days); return { at: iso(day), done: false }; };
assert.equal(remainingInfo(p, task(0), new Date(now.getTime() - 60000)).kind, 'today');
assert.equal(remainingInfo(p, task(1), now).colors.id, 'one-day');
assert.equal(remainingInfo(p, task(7), now).colors.id, 'one-week');
assert.equal(remainingInfo(p, task(8), now).colors.a, DEFAULTS.badgeColors.remaining.a);
assert.equal(remainingInfo(p, task(27), now).days, 27);
assert.equal(remainingInfo(p, task(-1), now).colors.a, DEFAULTS.remainingColors.overdue.a);
assert.equal(remainingInfo(p, { ...task(-1), done: true }, now).kind, 'done');
p.settings.remainingRules.unshift({ id: 'three-days', days: 3, a: '#010203', b: '#010203', border: '#010203' });
assert.equal(remainingInfo(p, task(1), now).colors.id, 'one-day', 'smallest applicable range has precedence regardless of settings order');
assert.equal(remainingInfo(p, task(3), now).colors.id, 'three-days');
p.settings.remainingRules.find(rule => rule.id === 'one-day').enabled = false;
assert.equal(remainingInfo(p, task(1), now).colors.id, 'three-days');
p.settings.remainingRulesEnabled = false;
assert.equal(remainingInfo(p, task(-1), now).colors.a, DEFAULTS.badgeColors.remaining.a);
assert.equal(contrastText('#000000', '#111111'), '#ffffff');
assert.equal(contrastText('#eeeeee', '#ffffff'), '#182e3a');
assert.equal(gradientAngle({ gradientAngle: 0 }), 0);
assert.equal(gradientAngle({ gradientAngle: 361 }), 360);
assert.equal(gradientAngle({ gradientAngle: 'bad' }), 120);
assert.equal(cardTint({ cardTint: 0 }), 0);
assert.equal(cardTint({ cardTint: 75 }), 50);
console.log('OK: today/overdue/done colors, inclusive 1/3/7-day thresholds, disabled ranges, nearest-first precedence, contrast and gradient controls.');
